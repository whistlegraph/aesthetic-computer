#!/usr/bin/env node
// chart.mjs — emit c/sailor-chart.h from the analysis, the loner deal:
// the Python/Node side owns measuring her, the C engine owns the score.
//
//   measures.json   → bars: start, length, her 4–5 beats (snapped to her
//                     strums), the chord she held
//   vox-notes.json  → her tuned notes (aesthetivox segmentation), onsets
//                     moved through lock-vox's time map so they match the
//                     locked stems the engine plays
//
//   node pop/sailor-song/bin/chart.mjs

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const LANE = resolve(HERE, "..");
// regularized clock (bin/regularize.mjs) when present: measures.reg.json + reg/timemap.txt
const RAW = process.env.SAILOR_CLOCK === "raw";   // v12: her take as played — no lock, no regularize, no cut
const REG = !RAW && existsSync(resolve(LANE, "measures.reg.json")) && existsSync(resolve(LANE, "src/vox/reg/timemap.txt"));
const CUT = REG && existsSync(resolve(LANE, "measures.cut.json")) && existsSync(resolve(LANE, "src/vox/cut/segmap.txt"));   // bin/splice.mjs
const M = JSON.parse(readFileSync(resolve(LANE, CUT ? "measures.cut.json" : REG ? "measures.reg.json" : "measures.json"), "utf8"));
const V = JSON.parse(readFileSync(resolve(LANE, "vox-notes.json"), "utf8")).notes;
const A = JSON.parse(readFileSync(resolve(LANE, "take.analysis.json"), "utf8"));

// lock-vox time map (sample pairs) → move note onsets with the stems
const mapPath = resolve(LANE, "src/vox/locked/timemap.txt");
const map = existsSync(mapPath)
  ? readFileSync(mapPath, "utf8").trim().split("\n").map((l) => l.split(" ").map((x) => Number(x) / 48000))
  : [[0, 0], [1e9, 1e9]];
const through = (map) => (t) => {
  let k = map.findIndex(([s]) => s > t); if (k <= 0) k = 1;
  const [s0, d0] = map[k - 1], [s1, d1] = map[k];
  return d0 + ((t - s0) / (s1 - s0)) * (d1 - d0);
};
const lockWarp = RAW ? (t) => t : through(map);
const regMap = REG ? readFileSync(resolve(LANE, "src/vox/reg/timemap.txt"), "utf8").trim().split("\n").map((l) => l.split(" ").map((x) => Number(x) / 48000)) : null;
const segs = CUT ? readFileSync(resolve(LANE, "src/vox/cut/segmap.txt"), "utf8").trim().split("\n").map((l) => l.split(" ").map(Number)) : [];
const cutOf = (t) => { for (const [a, b, o] of segs) if (t >= a && t < b) return t - a + o; return null; };
const regWarp = REG ? (t) => through(regMap)(lockWarp(t)) : lockWarp;
const warp = CUT ? (t) => cutOf(regWarp(t)) : regWarp;   // notes: sung → locked → regularized → cut (null inside a cut)

const CH = { "G#m": 0, Emaj7: 1, B: 2 };
const f = (x) => x.toFixed(4);
let h = `// sailor-chart.h — GENERATED by bin/chart.mjs; do not edit.
// Her clock and her melody. Bars are anchored on her strum motif
// (bin/measures.py); beats are snapped to her strums. Notes are her tuned
// line (bin/aesthetivox.py), onsets moved through the lock-vox map so they
// sit where the locked stems sing them. Pitches are MIDI in the guitar's
// frame; the engine adds CHART_TUNE semitones (+${A.tuningCents}¢ over A440).
#pragma once

#define CHART_TUNE ${(A.tuningCents / 100).toFixed(3)}
#define CHORD_GSM 0
#define CHORD_EMAJ7 1
#define CHORD_B 2

typedef struct { int n; double t, dur; int chord, nb; double beats[7]; } ChartBar;
typedef struct { double t, dur; int midi; } ChartNote;

#define CHART_NBARS ${M.bars.length}
static const ChartBar CHART_BARS[CHART_NBARS] = {
`;
for (const b of M.bars) {
  const beats = b.beats.slice(0, 7).map(f).join(", ");
  h += `  { ${b.n}, ${f(b.t)}, ${f(b.dur)}, ${CH[b.chord] ?? 0}, ${b.beats.length - 1}, { ${beats} } },\n`;
}
const NOTES = V.map((v) => ({ t: warp(v.t), e: warp(v.t + v.dur), midi: v.midi })).filter((n) => n.t !== null && n.e !== null && n.e > n.t).sort((a, b) => a.t - b.t);
h += `};\n\n#define CHART_NNOTES ${NOTES.length}\nstatic const ChartNote CHART_NOTES[CHART_NNOTES] = {\n`;
for (const n of NOTES) h += `  { ${f(n.t)}, ${f(n.e - n.t)}, ${n.midi} },\n`;
h += `};\n`;
writeFileSync(resolve(LANE, "c/sailor-chart.h"), h);
console.log(`✓ c/sailor-chart.h — ${M.bars.length} bars, ${NOTES.length} notes${CUT ? " (cut chart)" : ""}`);
