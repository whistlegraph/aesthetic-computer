#!/usr/bin/env node
// gm-timbre-layout.mjs — turn the measured GM timbre space into a grid.
//
// Reads bin/gm-timbre-space.json (produced by bin/gm-timbre-probe.c) and
// writes Sources/MenuBand/GMTimbreLayout.swift: a 128-entry permutation
// placing every GM program in the picker's 8 × 16 grid by how it SOUNDS
// instead of by its catalogue number.
//
// The layout follows Wessel's Figure 1 directly — brightness vertical,
// bite horizontal:
//
//   · programs sorted by brightness, descending → 16 rows of 8
//     (row 0 = brightest, matching "the sounds at the top of plot are
//      bright, and as one moves towards the bottom the timbres become
//      progressively more mellow")
//   · inside each row, sorted by bite ascending, left → right
//     (his horizontal axis points at "MORE BITE")
//
// Run:  node bin/gm-timbre-layout.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const COLS = 8;
const ROWS = 16;

const space = JSON.parse(readFileSync(join(root, "bin/gm-timbre-space.json"), "utf8"));
if (space.programs.length !== COLS * ROWS) {
  throw new Error(`expected ${COLS * ROWS} programs, got ${space.programs.length}`);
}

// Brightest first. Ties break on bite so the sort is total and the output
// is byte-stable across runs.
const byBrightness = [...space.programs].sort(
  (a, b) => b.brightness - a.brightness || b.bite - a.bite || a.program - b.program,
);

// programAtSlot[slot] = GM program drawn in that cell.
const programAtSlot = [];
for (let row = 0; row < ROWS; row += 1) {
  const band = byBrightness.slice(row * COLS, row * COLS + COLS);
  band.sort((a, b) => a.bite - b.bite || a.program - b.program);
  for (const entry of band) programAtSlot.push(entry.program);
}

const slotForProgram = new Array(128);
programAtSlot.forEach((p, slot) => { slotForProgram[p] = slot; });

// A permutation or nothing — a dropped or doubled program would silently
// make patches unreachable in the picker.
if (new Set(programAtSlot).size !== 128 || slotForProgram.some((s) => s === undefined)) {
  throw new Error("layout is not a permutation of 0..127");
}

const rowsSwift = (arr) => {
  const out = [];
  for (let i = 0; i < arr.length; i += COLS) {
    out.push("        " + arr.slice(i, i + COLS).map((n) => String(n).padStart(3)).join(", ") + ",");
  }
  return out.join("\n");
};

const coords = space.programs
  .map((p) => `        (${p.brightness.toFixed(4)}, ${p.bite.toFixed(4)}),  // ${p.program}`)
  .join("\n");

const swift = `// GMTimbreLayout.swift — GENERATED by bin/gm-timbre-layout.mjs. Do not edit.
//
// Source measurements: bin/gm-timbre-space.json, from bin/gm-timbre-probe.c
// (${space.programs.length} programs at ${space.pitch_name} = ${space.pitch_hz} Hz, loudness-equalized,
// gm_set_organic(0)). Regenerate with:
//
//     cc -O2 -I Sources/CGMSynth/include bin/gm-timbre-probe.c \\
//        Sources/CGMSynth/gm_synth.c -lm -o /tmp/gm-timbre-probe
//     /tmp/gm-timbre-probe > bin/gm-timbre-space.json
//     node bin/gm-timbre-layout.mjs
//
// After David Wessel, "Timbre Space as a Musical Control Structure",
// Computer Music Journal 3(2), 1979, pp. 45-52. The axes here are the
// ACOUSTIC CORRELATES Wessel used to interpret his measured dimensions —
// a Zwicker-style excitation-pattern centroid for brightness, onset rate
// and cross-band onset spread for bite. There were no listeners and no
// multidimensional scaling, so this is a proxy for his space, not his
// space. It is also stimulus-set-relative: these coordinates describe
// THIS synth at THIS pitch, and warp if either changes.

import Foundation

enum GMTimbreLayout {
    static let cols = ${COLS}
    static let rows = ${ROWS}

    /// Grid slot (row * cols + col) → GM program drawn there.
    /// Row 0 is the brightest band; within a row, bite increases rightward.
    static let programAtSlot: [Int] = [
${rowsSwift(programAtSlot)}
    ]

    /// GM program → its grid slot. Inverse of \`programAtSlot\`.
    static let slotForProgram: [Int] = [
${rowsSwift(slotForProgram)}
    ]

    /// Normalized (brightness, bite) per GM program, both 0…1 across this
    /// catalogue. Used for tinting and for any distance the app wants.
    static let coordinates: [(brightness: Double, bite: Double)] = [
${coords}
    ]

    /// Euclidean distance between two programs in the measured space.
    /// The lever the picker never had: "what else sounds like this".
    static func distance(_ a: Int, _ b: Int) -> Double {
        guard a >= 0, a < 128, b >= 0, b < 128 else { return .infinity }
        let p = coordinates[a], q = coordinates[b]
        let db = p.brightness - q.brightness, dt = p.bite - q.bite
        return (db * db + dt * dt).squareRoot()
    }
}
`;

writeFileSync(join(root, "Sources/MenuBand/GMTimbreLayout.swift"), swift);

// Human-readable check on stderr — the layout is only worth shipping if a
// musician recognizes the rows.
const NAMES = {
  0: "Ac Grand", 4: "Rhodes", 11: "Vibraphone", 16: "Drawbar Org", 19: "Church Org",
  24: "Nylon Gtr", 30: "Dist Gtr", 33: "Finger Bass", 40: "Violin", 42: "Cello",
  47: "Timpani", 48: "Str Ens", 52: "Choir", 56: "Trumpet", 65: "Alto Sax",
  71: "Clarinet", 73: "Flute", 78: "Whistle", 81: "Saw Lead", 89: "Warm Pad",
  115: "Woodblock", 126: "Applause", 127: "Gunshot",
};
const at = (p) => NAMES[p] ? `${p}(${NAMES[p]})` : String(p);
process.stderr.write("grid, brightest row first; bite increases rightward\n");
for (let row = 0; row < ROWS; row += 1) {
  const slots = programAtSlot.slice(row * COLS, row * COLS + COLS);
  process.stderr.write(`  row ${String(row).padStart(2)}  ${slots.map(at).join("  ")}\n`);
}
process.stderr.write("\nwrote Sources/MenuBand/GMTimbreLayout.swift\n");
