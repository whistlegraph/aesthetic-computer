#!/usr/bin/env node
// gen-entries.mjs — write entries.tex, index.tex and review.html from
// spells.json joined with e2e-summary.json (and approvals.json, if present).
//
//   node papers/arxiv-magicians-manual/gen-entries.mjs
//
// spells.json is the source. Each spell's `cast` line is what the browser
// test saw; where it is absent the line is derived from the test summary.
// review.html is a local page for watching the test clips (./clips/*.mp4,
// not committed) and approving each spell; it saves approvals.json.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const read = (f) => JSON.parse(readFileSync(join(HERE, f), "utf8"));
const { spells } = read("spells.json");
const summary = read("e2e-summary.json");
const approvals = existsSync(join(HERE, "approvals.json")) ? read("approvals.json") : {};
const cases = Object.fromEntries(summary.cases.map((c) => [c.id, c]));
const HANDLES = 113;

const esc = (s) => String(s)
  .replace(/\\/g, "\\textbackslash{}")
  .replace(/([#$%&_{}])/g, "\\$1")
  .replace(/~/g, "\\textasciitilde{}")
  .replace(/\^/g, "\\textasciicircum{}")
  .replace(/'/g, "'");
const slug = (s) => s.replace(/[^a-z0-9]+/gi, "-").replace(/^-|-$/g, "").slice(0, 40) || "x";

// Signs first, then letters.
const isSign = (n) => !/^[a-z]/i.test(n);
const SIGNS = ["+", "@handle", "@handle/piece", "#code", "$code", "!code"];
const ordered = [
  ...SIGNS.map((n) => spells.find((s) => s.name === n)).filter(Boolean),
  ...spells.filter((s) => !isSign(s.name)).sort((a, b) => a.name.localeCompare(b.name)),
];
ordered.forEach((s, i) => { s.label = `sp:${i + 1}`; });
const byName = Object.fromEntries(ordered.map((s) => [s.name, s]));

// What the test saw, in a sentence.
function castLine(s) {
  if (s.cast) return s.cast;
  const t = s.test || "";
  if (t.startsWith("not cast")) return `Not cast: ${t.split(": ")[1]}.`.replace(/^Not cast: (.)/, (m, c) => `Not cast: ${c}`);
  const c = cases[t];
  if (!c) return "Not tested.";
  if (!c.path) return "Left the page.";
  const moved = c.path !== (c.startPath || "/");
  if (!moved) return "Stayed at the prompt.";
  let line = `Opened ${c.path}.`;
  if (c.backKey) line += c.backPath === "/prompt" || c.backPath === "/" ? " Esc came back." : " Esc did not leave.";
  return line;
}
// A stable verdict word for the review page and the book's tally.
function verdict(s) {
  const line = castLine(s);
  if (/^Not cast|^Not confirmed|^Not tested/.test(line)) return "untested";
  if (/nothing visible|did not leave|Left the site/.test(line)) return "differs";
  return "works";
}

// ---- entries.tex ----------------------------------------------------------
const VIG = { prompt: "\\vigcorner", list: "\\vigcursor", hi: "\\vigdoors", handle: "\\vighandle", rect: "\\vigrect" };
let tex = "% Generated by gen-entries.mjs from spells.json. Do not edit by hand.\n";
let letter = null;
for (const s of ordered) {
  const L = isSign(s.name) ? "signs" : s.name[0].toUpperCase();
  if (L !== letter) {
    letter = L;
    tex += `\n\\letterhead{${L === "signs" ? "Signs" : L}}\n`;
  }
  const fields = [];
  if (s.needs) fields.push(["needs", esc(s.needs)]);
  if (s.leave) fields.push(["leave by", esc(s.leave)]);
  if (s.opened != null) fields.push(["opened by", `${s.opened} of ${HANDLES} handles${s.openedNote ? `, ${esc(s.openedNote)}` : ""}`]);
  fields.push(["cast", esc(castLine(s))]);
  if (s.also?.length) fields.push(["see", s.also.filter((n) => byName[n]).map((n) => `\\spl{${esc(n)}}`).join(", ")]);
  tex += `\\spellentry{${esc(s.name)}}{${s.arg ? esc(s.arg) : ""}}{${esc(s.kind)}}{${s.label}}{${VIG[s.name] || ""}}{%\n${esc(s.desc)}}{%\n`;
  tex += fields.map(([k, v]) => `\\field{${k}}{${v}}`).join("\n") + "}\n";
}
writeFileSync(join(HERE, "entries.tex"), tex);

// ---- index.tex: by what you want to do ------------------------------------
const PURPOSES = [
  ["start", "To begin"], ["people", "To find people"], ["account", "To be someone"],
  ["sigils", "To name a thing"], ["paint", "To paint"], ["sound", "To make sound"],
  ["words", "To play with words"], ["record", "To record and share"], ["write", "To write your own"],
];
let idx = "% Generated by gen-entries.mjs. Do not edit by hand.\n";
for (const [key, title] of PURPOSES) {
  const list = ordered.filter((s) => s.for?.includes(key));
  if (!list.length) continue;
  idx += `\\indexhead{${title}}\n`;
  idx += list.map((s) => `\\indexrow{${esc(s.name)}}{${s.label}}`).join("\n") + "\n";
}
writeFileSync(join(HERE, "index.tex"), idx);

// ---- tally.tex ------------------------------------------------------------
const tally = { works: 0, differs: 0, untested: 0 };
for (const s of ordered) tally[verdict(s)]++;
writeFileSync(join(HERE, "tally.tex"),
  `% Generated by gen-entries.mjs.\n\\newcommand{\\spellcount}{${ordered.length}}\n\\newcommand{\\tallyworks}{${tally.works}}\n\\newcommand{\\tallydiffers}{${tally.differs}}\n\\newcommand{\\tallyuntested}{${tally.untested}}\n\\newcommand{\\testdate}{${new Date(summary.at).toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric", timeZone: "UTC" })}}\n`);

// ---- review.html ----------------------------------------------------------
const clipFor = (s) => {
  const t = s.test || "";
  if (!cases[t] && !t.startsWith("flow:")) return null;
  return `clips/${slug(t)}.mp4`;
};
const rows = ordered.map((s) => ({
  name: s.name, arg: s.arg || "", kind: s.kind, desc: s.desc, needs: s.needs || "", leave: s.leave || "",
  opened: s.opened ?? null, cast: castLine(s), verdict: verdict(s), test: s.test || "", clip: clipFor(s),
  approved: approvals[s.name]?.status || "", note: approvals[s.name]?.note || "",
}));
const html = `<!doctype html><meta charset="utf-8"><title>Spells review</title>
<meta name="viewport" content="width=device-width,initial-scale=1">
<style>
:root{--bg:#f6f4f8;--fg:#2a2433;--mut:#77707f;--card:#fff;--line:#ddd8e4;--ok:#1f7a4a;--bad:#b4483a;--warn:#9a6a00}
@media(prefers-color-scheme:dark){:root{--bg:#17151c;--fg:#ece8f2;--mut:#9a93a6;--card:#221f2a;--line:#3a3545;--ok:#5fd08f;--bad:#ff8a7a;--warn:#f0c060}}
body{margin:0;background:var(--bg);color:var(--fg);font:15px/1.45 -apple-system,system-ui,sans-serif}
header{position:sticky;top:0;background:var(--bg);border-bottom:1px solid var(--line);padding:12px 16px;z-index:2;display:flex;gap:14px;align-items:center;flex-wrap:wrap}
h1{font-size:17px;margin:0}
.count{color:var(--mut)}
button,select{font:inherit;padding:5px 10px;border:1px solid var(--line);border-radius:6px;background:var(--card);color:var(--fg);cursor:pointer}
main{display:grid;grid-template-columns:repeat(auto-fill,minmax(360px,1fr));gap:14px;padding:16px}
.card{background:var(--card);border:1px solid var(--line);border-radius:10px;overflow:hidden;display:flex;flex-direction:column}
.card.approved{border-color:var(--ok)}.card.flagged{border-color:var(--bad)}
video{width:100%;aspect-ratio:660/460;background:#111;display:block}
.noclip{aspect-ratio:660/460;display:grid;place-items:center;color:var(--mut);background:rgba(127,127,127,.12);font-size:13px;text-align:center;padding:0 20px}
.body{padding:10px 12px 12px;display:flex;flex-direction:column;gap:6px}
.name{font:600 16px ui-monospace,Menlo,monospace}
.kind{color:var(--mut);font-style:italic;float:right}
dl{margin:0;display:grid;grid-template-columns:76px 1fr;gap:2px 8px;font-size:13px}
dt{color:var(--mut)}dd{margin:0}
.v{font-weight:600}.v.works{color:var(--ok)}.v.differs{color:var(--bad)}.v.untested{color:var(--warn)}
.acts{display:flex;gap:6px;margin-top:4px}
.acts button.on-approved{background:var(--ok);color:#fff;border-color:var(--ok)}
.acts button.on-flagged{background:var(--bad);color:#fff;border-color:var(--bad)}
input.note{flex:1;font:inherit;padding:5px 8px;border:1px solid var(--line);border-radius:6px;background:transparent;color:var(--fg);min-width:0}
</style>
<header><h1>Spells review</h1><span class="count" id="count"></span>
<select id="filter"><option value="">All</option><option value="works">Test: works</option><option value="differs">Test: differs from the book</option><option value="untested">Test: untested</option><option value="todo">Not yet reviewed</option></select>
<button id="save">Save approvals.json</button>
<span class="count">Tested ${summary.at.slice(0, 10)} as a ${summary.visitor}.</span></header>
<main id="main"></main>
<script>
const ROWS=${JSON.stringify(rows)};
const KEY="spells-approvals";
let state={};try{state=JSON.parse(localStorage.getItem(KEY)||"{}")}catch{}
for(const r of ROWS){if(!state[r.name]&&r.approved)state[r.name]={status:r.approved,note:r.note}}
const main=document.getElementById("main"),filter=document.getElementById("filter");
const persist=()=>{try{localStorage.setItem(KEY,JSON.stringify(state))}catch{}};
function draw(){
  main.textContent="";let done=0;
  for(const r of ROWS){
    const st=state[r.name]||{};if(st.status)done++;
    const f=filter.value;if(f==="todo"?st.status:(f&&r.verdict!==f))continue;
    const card=document.createElement("div");card.className="card "+(st.status||"");
    if(r.clip){const v=document.createElement("video");v.src=r.clip;v.controls=true;v.preload="metadata";v.playsInline=true;
      v.onerror=()=>{const n=document.createElement("div");n.className="noclip";n.textContent="Clip not found: "+r.clip;v.replaceWith(n)};card.append(v)}
    else{const n=document.createElement("div");n.className="noclip";n.textContent=r.test||"No test";card.append(n)}
    const b=document.createElement("div");b.className="body";
    const h=document.createElement("div");
    const k=document.createElement("span");k.className="kind";k.textContent=r.kind;
    const nm=document.createElement("span");nm.className="name";nm.textContent=r.name+(r.arg?" "+r.arg:"");h.append(k,nm);b.append(h);
    const dl=document.createElement("dl");
    const add=(t,d,cls)=>{if(!d)return;const dt=document.createElement("dt");dt.textContent=t;const dd=document.createElement("dd");dd.textContent=d;if(cls)dd.className=cls;dl.append(dt,dd)};
    add("Book says",r.desc);add("Needs",r.needs);add("Leave by",r.leave);add("Opened by",r.opened==null?"":r.opened+" of 113 handles");
    add("Test saw",r.cast);add("Verdict",r.verdict,"v "+r.verdict);b.append(dl);
    const acts=document.createElement("div");acts.className="acts";
    const mk=(label,val)=>{const x=document.createElement("button");x.textContent=label;if(st.status===val)x.className="on-"+val;
      x.onclick=()=>{state[r.name]={...(state[r.name]||{}),status:st.status===val?"":val};persist();draw()};return x};
    const note=document.createElement("input");note.className="note";note.placeholder="note";note.value=st.note||"";
    note.onchange=()=>{state[r.name]={...(state[r.name]||{}),note:note.value};persist()};
    acts.append(mk("Approve","approved"),mk("Flag","flagged"),note);b.append(acts);card.append(b);main.append(card);
  }
  document.getElementById("count").textContent=done+" of "+ROWS.length+" reviewed";
}
filter.onchange=draw;
document.getElementById("save").onclick=()=>{
  const a=document.createElement("a");a.href=URL.createObjectURL(new Blob([JSON.stringify(state,null,1)],{type:"application/json"}));
  a.download="approvals.json";a.click();
};
draw();
</script>`;
writeFileSync(join(HERE, "review.html"), html);
console.log(`${ordered.length} spells: ${tally.works} work, ${tally.differs} differ, ${tally.untested} untested`);
