#!/usr/bin/env node
// extract-brushes.mjs — write brushes.json from the game's own help.
//
//   node papers/arxiv-nopaint-brushbook/extract-brushes.mjs
//
// No Paint (2021) carries a help page for every brush in its Index event
// sheet (function ShowHelp): a title line with the options, a few lines of
// description, the range of each option, and who made it. The same sheet
// holds the two weighted tables the game draws its proposals from. This reads
// both out of the Construct source (nopaint/construct/, a private product
// directory) so the book states what the game states.

import { readFileSync, writeFileSync } from "node:fs";

const sheet = JSON.parse(readFileSync(new URL("../../nopaint/construct/eventSheets/Index.json", import.meta.url), "utf8"));
const kids = (node) => node.children || node.events || [];
const find = (node, name) => node.eventType === "function-block" && node.functionName === name ? node
  : kids(node).map((child) => find(child, name)).find(Boolean);
const each = (node, visit) => { visit(node); kids(node).forEach((child) => each(child, visit)); };
const literal = (text) => text.startsWith('"') ? text.slice(1, -1).replaceAll('""', '"') : text;
const plain = (text) => text.replace(/\[\/?[a-z]+(?:=[^\]]*)?\]/gi, "").replace(/\s+/g, " ").trim();

// The weighted tables.
const tables = {};
let table = null;
each(sheet, (node) => {
  for (const action of node.actions || []) {
    if (action.objectClass !== "AdvancedRandom") continue;
    if (action.id === "createProbabilityTable") tables[table = literal(action.parameters.name)] = {};
    if (action.id === "addProbabilityEntry" && table) {
      const name = literal(action.parameters.value);
      tables[table][name] = +((tables[table][name] || 0) + Number(action.parameters.weight)).toFixed(3);
    }
  }
});

// The help pages.
const pages = new Map();
each(find(sheet, "ShowHelp"), (node) => {
  const named = (node.conditions || []).find((c) => c.id === "compare-eventvar" && c.parameters.variable === "command" && c.parameters.comparison === 0);
  if (!named) return;
  const texts = [];
  each(node, (inner) => (inner.actions || []).forEach((a) => { if (a.id === "set-text") texts.push(a.parameters.text); }));
  if (texts.length && !pages.has(literal(named.parameters.value))) pages.set(literal(named.parameters.value), texts);
});

function page(name, text) {
  const call = (fn) => [...text.matchAll(new RegExp(`Functions\\.${fn}\\(\\s*(command|"(?:[^"]|"")*")\\s*,\\s*"((?:[^"]|"")*)"\\s*\\)`, "g"))];
  const title = call("HelpTitleLine")[0], by = call("HelpByLine")[0];
  const rest = text.replace(/Functions\.\w+\([^)]*\)/g, "");
  const desc = plain([...rest.matchAll(/"((?:[^"]|"")*)"/g)].map((m) => m[1].replaceAll('""', '"')).join(" "));
  return {
    name, options: title ? plain(title[2]) : "",
    desc,
    ranges: call("HelpParamDocLine").map((m) => ({ option: plain(literal(m[1])), range: plain(m[2]) })),
    by: by ? literal(by[1]) : null, color: by ? by[2].replace(/^#/, "").toLowerCase() : null,
  };
}

const brushes = [];
for (const [name, texts] of pages) {
  if (!name || name.startsWith("@") || name === "Reset") continue;
  const entry = page(name, texts[0]);
  // Stamp has no sentence, only the painters whose drawings it places.
  const names = [...new Set(texts.flatMap((text) => [...text.matchAll(/Functions\.HelpName\(\s*"([^"]*)"/g)].map((m) => m[1])))];
  if (names.length) { entry.painters = names; entry.desc = ""; }
  // Camera has a desktop page and a phone page; keep both option lines.
  if (texts.length > 1) entry.variants = texts.slice(1).map((text) => { const v = page(name, text); return { options: v.options, ranges: v.ranges }; })
    .filter((v) => v.options !== entry.options);
  if (entry.variants && !entry.variants.length) delete entry.variants;
  const drawn = Object.entries(tables).find(([, rows]) => name in rows);
  entry.table = drawn ? drawn[0] : null;
  entry.weight = drawn ? drawn[1][name] : null;
  brushes.push(entry);
}
brushes.sort((a, b) => a.name.localeCompare(b.name));
const painters = [...pages.keys()].filter((name) => name.startsWith("@")).map((name) => name.slice(1));
const totals = Object.fromEntries(Object.entries(tables).map(([name, rows]) => [name, +Object.values(rows).reduce((a, b) => a + b, 0).toFixed(3)]));

writeFileSync(new URL("./brushes.json", import.meta.url), JSON.stringify({
  note: "Generated by extract-brushes.mjs from the ShowHelp function and the probability tables of No Paint's Index event sheet (2021 project, resaved by Construct r495.2). options, desc, ranges and by are the game's own help text with its colour tags removed. table and weight say which weighted table proposes the brush on its own (null: only by name at the prompt); the game picks one of the two tables at even odds, then a brush by weight.",
  totals, painters, brushes,
}, null, 1) + "\n");
console.log(`${brushes.length} brushes, ${painters.length} painters, tables ${JSON.stringify(totals)}`);
