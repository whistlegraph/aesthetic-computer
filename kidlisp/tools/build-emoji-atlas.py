"""Regenerate data.mjs with fonttools==4.69.1 pillow==13.0.0 uharfbuzz==0.57.0.

Run python kidlisp/tools/build-emoji-atlas.py from any directory.
The optional positional directory caches the two verified upstream downloads.
"""
import base64
import hashlib
import io
import json
from pathlib import Path
import sys
import tempfile
import urllib.request

from fontTools.ttLib import TTFont
from PIL import Image
import uharfbuzz as hb

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "system/public/aesthetic.computer/disks/common/emoji-atlas/data.mjs"
FONT = "https://raw.githubusercontent.com/googlefonts/noto-emoji/e20cbc2bbec1926686be9f9bee7d1d2cfa1fea0e/2D/fonts/NotoColorEmoji.ttf"
LIST = "https://www.unicode.org/Public/18.0.0/emoji/emoji-test.txt"


def load(cache, name, url, digest):
    path = cache / name
    if not path.exists():
        path.write_bytes(urllib.request.urlopen(url, timeout=90).read())
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != digest:
        raise ValueError(f"Unexpected SHA-256 for {path}")
    return data


def encode(png):
    image = Image.open(io.BytesIO(png)).convert("RGBA")
    bounds = image.getbbox()
    if not bounds:
        raise ValueError("Empty glyph")
    image = image.crop(bounds)
    image.thumbnail((16, 16), Image.Resampling.LANCZOS)
    tile = Image.new("RGBA", (16, 16))
    tile.paste(image, ((16 - image.width) // 2, (16 - image.height) // 2))
    quantized = tile.quantize(colors=16, method=Image.Quantize.FASTOCTREE)
    palette = bytes(quantized.getpalette("RGBA")[:64]).ljust(64, b"\0")
    indices = quantized.tobytes()
    pairs = bytes((a << 4) | b for a, b in zip(indices[::2], indices[1::2]))
    return palette + pairs


def generate(cache):
    cache.mkdir(parents=True, exist_ok=True)
    data = load(cache, "font.ttf", FONT, "15671215ab769fdc7162a045d56fd7d7e477c51b04e6b3c761d914d8fdd6cc44")
    listed = load(cache, "emoji-test.txt", LIST, "8f3735cda1f92a779d78af67cf86066bb1f07143dc22f2ac29394d9bc57ab21a")
    font = TTFont(io.BytesIO(data))
    shaper = hb.Font(hb.Face(data))
    strike = font["CBDT"].strikeData[0]
    keys, tiles = [], []
    for row in listed.decode("utf-8").splitlines():
        entry = row.partition("#")[0].strip()
        if not entry:
            continue
        codes, status = map(str.strip, entry.split(";"))
        if status not in ("component", "fully-qualified"):
            continue
        glyph = "".join(chr(int(code, 16)) for code in codes.split())
        buffer = hb.Buffer()
        buffer.add_str(glyph)
        buffer.guess_segment_properties()
        hb.shape(shaper, buffer)
        if len(buffer.glyph_infos) != 1 or not buffer.glyph_infos[0].codepoint:
            raise ValueError(f"Missing ligature for {codes}")
        name = font.getGlyphName(buffer.glyph_infos[0].codepoint)
        keys.append(glyph)
        tiles.append(encode(strike[name].imageData))
    if len(set(keys)) != 3972 or len(keys) != 3972:
        raise ValueError("Unexpected Unicode 18 emoji count")
    pages = [base64.b64encode(b"".join(tiles[i:i + 64])).decode("ascii")
             for i in range(0, len(keys), 64)]
    OUT.write_text("// Generated by kidlisp/tools/build-emoji-atlas.py.\n"
                   + "export const keys = " + json.dumps(" ".join(keys), ensure_ascii=False)
                   + ";\nexport const pages = [\n"
                   + "".join(f'  "{page}",\n' for page in pages) + "];\n", encoding="utf-8")


if __name__ == "__main__":
    with tempfile.TemporaryDirectory() as tmp:
        generate(Path(sys.argv[1]) if len(sys.argv) > 1 else Path(tmp))
