#!/bin/bash
# offload.sh — put the sung-intelligibility loop on a bigger machine.
#
# neo is the 8 GB controller and kept wedging under whisper + swift + render
# (load 227, disk 99% full on 2026-09-21). Everything this loop needs is
# portable, so it runs on poorslice (M1 Pro, 16 GB, 765 GB free, sudo-free
# $HOME toolchain — see memory poorslice-render-node):
#
#   ~/singbench/            a SELF-CONTAINED Swift package for `singrender`
#                           (Package.swift written here; CSinger + the two
#                           Swift files rsynced with symlinks dereferenced,
#                           so none of Menu Band's dependency graph travels)
#   ~/whisper/bin/whisper-cli   built from source, STATIC. (Relocating the
#                           Homebrew binary does not work: brew's ggml compiles
#                           in one backend search path, /opt/homebrew/Cellar/
#                           ggml/<v>/libexec, and looks nowhere else — it never
#                           tries the executable's own directory, and GGML_BACKEND_PATH
#                           wants a single file. With no sudo you cannot make
#                           that path exist, so ggml finds no device and aborts
#                           in ggml_backend_dev_init. A static build has its
#                           backends linked in and just works.)
#   ~/aesthetic-computer/   the lane (bin, scores, members, hear) + the model
#   $TMPDIR/mnp-hear/speech-cache  the spoken TTS source, so lines already
#                           spoken on neo need no voice installed there
#
# Usage:  bash bin/offload.sh [host]        (default: poorslice)
set -euo pipefail
HOST="${1:-poorslice}"
LANE="$(cd "$(dirname "$0")/.." && pwd)"
REPO="$(cd "$LANE/../../.." && pwd)"
MB="$REPO/slab/menuband"
RLANE="aesthetic-computer/grants/culturehub-la-2026/macneopolitan"

echo "→ $HOST: directories"
ssh "$HOST" 'mkdir -p ~/singbench/Sources/{CSinger,SingRender} ~/whisper ~/aesthetic-computer/recap/models ~/'"$RLANE"'/{bin,scores,members,hear}'

echo "→ $HOST: the renderer's sources (symlinks dereferenced)"
rsync -aL --delete "$MB/Sources/CSinger/" "$HOST:singbench/Sources/CSinger/"
rsync -aL "$MB/Sources/SingRender/main.swift" "$MB/Sources/MenuBand/MenuBandSinger.swift" "$HOST:singbench/Sources/SingRender/"

echo "→ $HOST: a package with no dependency graph"
ssh "$HOST" 'cat > ~/singbench/Package.swift' <<'PKG'
// swift-tools-version:5.9
// Generated by grants/culturehub-la-2026/macneopolitan/bin/offload.sh.
// The same two targets slab/menuband builds for `singrender`, with none of
// the app's dependencies — so an evaluation host needs only Swift + the
// synced sources. Flags match the real package (and live/Makefile).
import PackageDescription
let package = Package(
    name: "singbench",
    platforms: [.macOS(.v13)],
    targets: [
        .target(name: "CSinger", path: "Sources/CSinger", publicHeadersPath: "include",
                cSettings: [.headerSearchPath("world"), .unsafeFlags(["-O3", "-ffast-math"])],
                cxxSettings: [.headerSearchPath("world"), .unsafeFlags(["-O3", "-ffast-math"])]),
        .executableTarget(name: "singrender", dependencies: ["CSinger"], path: "Sources/SingRender"),
    ]
)
PKG

echo "→ $HOST: the lane"
rsync -a "$LANE/bin/" "$HOST:$RLANE/bin/"
rsync -a "$LANE/scores/" "$HOST:$RLANE/scores/"
rsync -a --exclude 'speech' --exclude '*.m4a' "$LANE/members/" "$HOST:$RLANE/members/"
rsync -a "$LANE/PIECE.md" "$HOST:$RLANE/"
rsync -a "$LANE/hear/" "$HOST:$RLANE/hear/"          # results so far — never clobbered

echo "→ $HOST: whisper (cmake + whisper.cpp in \$HOME, once) and the model"
ssh "$HOST" 'set -e
  if [ ! -x ~/whisper/bin/whisper-cli ]; then
    if [ ! -x ~/cmake/CMake.app/Contents/bin/cmake ]; then
      cd ~ && curl -sL -o cmake.tar.gz https://github.com/Kitware/CMake/releases/download/v4.1.2/cmake-4.1.2-macos-universal.tar.gz
      tar xzf cmake.tar.gz && mv cmake-4.1.2-macos-universal cmake && rm cmake.tar.gz
    fi
    export PATH=$HOME/cmake/CMake.app/Contents/bin:$PATH
    cd ~ && [ -d whisper.cpp ] || git clone -q --depth 1 --branch v1.9.2 https://github.com/ggml-org/whisper.cpp.git
    cd whisper.cpp
    cmake -B build -DCMAKE_BUILD_TYPE=Release -DWHISPER_BUILD_TESTS=OFF -DBUILD_SHARED_LIBS=OFF >/dev/null
    cmake --build build --config Release -j 8 --target whisper-cli >/dev/null
    mkdir -p ~/whisper/bin && cp build/bin/whisper-cli ~/whisper/bin/
  fi
  ~/whisper/bin/whisper-cli --help >/dev/null 2>&1 && echo "  whisper-cli ok"'
rsync -a "$REPO/recap/models/ggml-small.en.bin" "$HOST:aesthetic-computer/recap/models/"

echo "→ $HOST: the spoken-source cache"
LOCAL_CACHE="${TMPDIR%/}/mnp-hear/speech-cache"
ssh "$HOST" 'mkdir -p "${TMPDIR%/}/mnp-hear/speech-cache"'
RCACHE=$(ssh "$HOST" 'echo "${TMPDIR%/}/mnp-hear/speech-cache"')
[ -d "$LOCAL_CACHE" ] && rsync -a "$LOCAL_CACHE/" "$HOST:$RCACHE/"

echo "→ $HOST: build"
ssh "$HOST" 'cd ~/singbench && swift build -c release --product singrender 2>&1 | grep -E "error|Build complete" | tail -3'

echo "→ $HOST: smoke"
ssh "$HOST" 'export PATH=$HOME/whisper/bin:$HOME/bin:$HOME/node/bin:$PATH
  cd ~/'"$RLANE"' && SINGRENDER=$HOME/singbench/.build/release/singrender \
  node bin/hear.mjs scores/dialog-06-six-minutes.mbscore --tag smoke-remote --no-spoken 2>&1 | tail -4'
echo "✓ $HOST ready"
