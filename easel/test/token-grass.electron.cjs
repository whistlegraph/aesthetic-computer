const {app,BrowserWindow,ipcMain}=require('electron');
const assert=require('node:assert/strict'),path=require('node:path'),fs=require('node:fs');
const wait=ms=>new Promise(r=>setTimeout(r,ms));let win;
(async()=>{
 await app.whenReady();ipcMain.handle('native-prox-title',()=>({glyphs:[]}));
 win=new BrowserWindow({show:false,width:620,height:400,webPreferences:{preload:path.resolve('easel/desktop/preload.cjs'),contextIsolation:true,sandbox:true,backgroundThrottling:false}});
 await win.loadFile(path.resolve('easel/desktop/index.html'));
 const js=s=>win.webContents.executeJavaScript(s);
 win.webContents.send('theme',{background:'#142131',foreground:'#fffbea',cursor:'#eeaacc'});
 await js(`document.body.dataset.phase='ready';window.updateConversation({entries:[{id:'u',kind:'user',text:'Make the wheels roll.'}]})`);
 const send=(name,value)=>win.webContents.send('output','\x1b]777;easel-'+name+':'+JSON.stringify(value)+'\x07');
 send('prompt',{text:'',cursor:0,activity:"I'm giving those wheels a little momentum",feedback:'Writing'});await wait(150);
 assert.equal(await js(`document.getElementById('token-grass').hidden`),true);
 await js(`window.glyphs=[];const c=document.getElementById('token-grass').getContext('2d'),f=c.fillText.bind(c);c.fillText=(s,...args)=>{glyphs.push(s);return f(s,...args)};void 0`);
 const delta='wheel.rotation += speed * dt;';
 send('token-grass',{delta});await wait(200);
 assert.equal(await js(`document.getElementById('token-grass').hidden`),false);
 assert.equal(await js(`getComputedStyle(document.getElementById('token-grass')).pointerEvents`),'none');
 assert.equal(await js(`glyphs.every(c=>${JSON.stringify(delta)}.includes(c))`),true,'Every visible glyph came from the delta');
 const bounds=await js(`(()=>{const d=document.getElementById('prompt-feedback').getBoundingClientRect(),g=document.getElementById('token-grass').getBoundingClientRect();return {feet:Math.abs(g.top-d.bottom)<12,inside:g.right<=innerWidth&&g.left>=0}})()`);
 assert(bounds.feet&&bounds.inside);
 fs.writeFileSync('/tmp/aesel-token-grass.png',(await win.webContents.capturePage()).toPNG());
 await wait(1400);assert.equal(await js(`document.getElementById('token-grass').hidden`),true,'No generated stream while quiet');
 await js('glyphs=[]');send('token-grass',{delta:'x'.repeat(100000)});await wait(90);
 assert((await js('glyphs.length'))<=144,'A burst cannot create unbounded blades');
 win.setSize(380,400);await wait(50);
 assert.equal(await js(`document.getElementById('token-grass').getBoundingClientRect().right<=innerWidth`),true);
 send('prompt',{text:'',cursor:0,activity:'',feedback:''});await wait(60);
 assert.equal(await js(`document.getElementById('token-grass').hidden`),true);
 console.log('PASS real glyphs, feet position, quiet decay, bounded bursts, narrow viewport, idle cleanup');
})().catch(e=>{console.error(e);process.exitCode=1}).finally(()=>{win?.destroy();app.quit()});
